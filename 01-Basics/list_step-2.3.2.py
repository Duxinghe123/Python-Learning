# Python 2.3.2：列表切片的步长（Step）
numbers = [10, 20, 30, 40, 50, 60]  # 创建数字列表
print(numbers[0:6:2])  # 从索引0开始，每次向右移动2个索引

numbers = [10, 20, 30, 40, 50, 60]  # 创建数字列表
print(numbers[::3])  # 从左往右，每次移动3个索引

numbers = [10, 20, 30, 40, 50, 60]  # 创建数字列表
print(numbers[::-1])  # 从右往左，每次移动1个索引，实现反转

numbers = [10, 20, 30, 40, 50, 60, 70, 80]  # 创建练习列表
print(numbers[0:8:2])
print(numbers[0:7:3])
print(numbers[::-1])
# print(numbers[0:8:-2]) 错误
print(numbers[::-2])  # 从右向左，每次移动2个索引 正确

numbers = [10, 20, 30, 40, 50]  # 创建数字列表
print(numbers[4:0:-2])  # 从索引4开始，向左每次移动2个索引
# 从索引4开始，依次访问索引4、2。结束位置是索引0，但切片不包含结束索引，所以数字10不会被取到。
